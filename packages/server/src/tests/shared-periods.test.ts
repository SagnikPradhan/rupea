import { periodOf } from '#lib/server/shared/periods.ts';
import { describe, expect, it } from 'vitest';

const day = (s: string) => Temporal.PlainDate.from(s);

describe('the period holding a day', () => {
	it.each([
		['month', '2026-08-29', undefined, '2026-08-01', '2026-08-31'],
		['month', '2026-02-10', undefined, '2026-02-01', '2026-02-28'],
		['year', '2026-08-29', undefined, '2026-01-01', '2026-12-31'],
		['month', '2026-05-10', '2026-04-25', '2026-04-25', '2026-05-24'],
		['month', '2026-05-24', '2026-04-25', '2026-04-25', '2026-05-24'],
		['month', '2026-05-25', '2026-04-25', '2026-05-25', '2026-06-24'],
		['year', '2027-01-15', '2026-04-01', '2026-04-01', '2027-03-31'],
		['month', '2026-04-10', '2026-04-25', '2026-03-25', '2026-04-24'],
		['year', '2026-02-10', '2026-04-01', '2025-04-01', '2026-03-31'],
		['month', '2026-03-01', '2026-01-31', '2026-02-28', '2026-03-30'],
		['month', '2026-03-30', '2026-01-31', '2026-02-28', '2026-03-30'],
		['month', '2026-03-31', '2026-01-31', '2026-03-31', '2026-04-29'],
		['year', '2025-03-01', '2024-02-29', '2025-02-28', '2026-02-27'],
		['year', '2028-03-01', '2024-02-29', '2028-02-29', '2029-02-27'],
		['month', '2026-04-25', '2026-04-25', '2026-04-25', '2026-05-24'],
		['month', '2026-01-31', '2026-01-31', '2026-01-31', '2026-02-27'],
		['month', '2026-02-27', '2026-01-31', '2026-01-31', '2026-02-27'],
		['month', '2026-02-28', '2026-01-31', '2026-02-28', '2026-03-30'],
		['month', '2026-04-29', '2026-01-31', '2026-03-31', '2026-04-29'],
		['month', '2026-04-30', '2026-01-31', '2026-04-30', '2026-05-30'],
		['month', '2026-05-01', '2026-01-31', '2026-04-30', '2026-05-30'],
		['month', '2028-02-28', '2028-01-31', '2028-01-31', '2028-02-28'],
		['month', '2028-02-29', '2028-01-31', '2028-02-29', '2028-03-30'],
		['month', '2026-02-27', '2026-01-30', '2026-01-30', '2026-02-27'],
		['month', '2026-02-28', '2026-01-30', '2026-02-28', '2026-03-29'],
		['month', '2026-03-30', '2026-01-30', '2026-03-30', '2026-04-29'],
		['month', '2026-02-27', '2026-01-29', '2026-01-29', '2026-02-27'],
		['month', '2026-02-28', '2026-01-29', '2026-02-28', '2026-03-28'],
		['month', '2026-03-29', '2026-01-29', '2026-03-29', '2026-04-28'],
		['month', '2028-02-28', '2028-01-29', '2028-01-29', '2028-02-28'],
		['month', '2028-02-29', '2028-01-29', '2028-02-29', '2028-03-28'],
		['year', '2025-02-27', '2024-02-29', '2024-02-29', '2025-02-27'],
		['year', '2025-02-28', '2024-02-29', '2025-02-28', '2026-02-27'],
		['year', '2026-02-28', '2024-02-29', '2026-02-28', '2027-02-27'],
		['year', '2028-02-29', '2024-02-29', '2028-02-29', '2029-02-27'],
		['month', '2026-01-15', '2026-01-31', '2025-12-31', '2026-01-30'],
		['month', '2026-02-15', '2026-03-31', '2026-01-31', '2026-02-27'],
		['month', '2026-02-28', '2026-03-31', '2026-02-28', '2026-03-30'],
		['year', '2023-06-01', '2024-02-29', '2023-02-28', '2024-02-28'],
	] as const)('puts %s of %s from %s in %s to %s', (length, d, start, from, to) => {
		const o = start ? { length, start: day(start) } : { length };
		expect(periodOf(day(d), o)).toEqual({ from: day(from), to: day(to) });
	});

	it.each([
		['month', '2026-01-31'],
		['month', '2026-03-31'],
		['month', '2028-01-29'],
		['year', '2024-02-29'],
	] as const)('tiles the days after a %s anchor of %s with no gap', (length, start) => {
		const days = Array.from({ length: 800 }, (_, i) =>
			day(start).subtract({ days: 40 }).add({ days: i }),
		);
		const periods = days.map((d) => periodOf(d, { length, start: day(start) }));

		for (const [i, p] of periods.entries()) {
			expect(Temporal.PlainDate.compare(p.from, days[i]!)).toBeLessThanOrEqual(0);
			expect(Temporal.PlainDate.compare(p.to, days[i]!)).toBeGreaterThanOrEqual(0);
			const next = periods[i + 1];
			if (next && !next.from.equals(p.from))
				expect(next.from.equals(p.to.add({ days: 1 }))).toBe(true);
		}
	});
});
