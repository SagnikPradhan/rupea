/** The words with what the merchants they name sell, so they can be compared with account names. */
export const described = (words: string): string =>
	[
		words,
		...Object.entries(MERCHANTS)
			.filter(([, names]) => names.some((n) => spells(words, n)))
			.map(([about]) => about),
	].join(' ');
